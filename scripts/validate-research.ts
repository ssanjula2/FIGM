import fs from 'node:fs';
import path from 'node:path';

async function validateResearchIntegrity() {
  console.log('====================================================');
  console.log('FIGM Research Integrity & Dynamic Metric Validator');
  console.log('====================================================');

  const evalSummaryPath = path.resolve(process.cwd(), 'benchmarks/eval-summary.json');
  const canonicalPath = path.resolve(process.cwd(), 'docs/evidence/canonical-evaluation.json');

  if (!fs.existsSync(evalSummaryPath)) {
    console.error('❌ ERROR: benchmarks/eval-summary.json not found. Run "npm run research:evaluate" first.');
    process.exit(1);
  }

  if (!fs.existsSync(canonicalPath)) {
    console.error('❌ ERROR: docs/evidence/canonical-evaluation.json not found. Run "npm run research:evaluate" first.');
    process.exit(1);
  }

  const evalSummary = JSON.parse(fs.readFileSync(evalSummaryPath, 'utf8'));
  const canonical = JSON.parse(fs.readFileSync(canonicalPath, 'utf8'));

  // 1. Provenance Validation
  if (!canonical.provenance || !canonical.provenance.dynamic) {
    console.error('❌ ERROR: Canonical evaluation artifact is missing dynamic provenance metadata!');
    process.exit(1);
  }

  const tp = evalSummary.overall.truePositives;
  const fp = evalSummary.overall.falsePositives;
  const fn = evalSummary.overall.falseNegatives;

  // 2. Dynamic Mathematical Formula Validation
  const computedPrecision = tp + fp > 0 ? tp / (tp + fp) : 0;
  const computedRecall = tp + fn > 0 ? tp / (tp + fn) : 0;
  const computedF1 = computedPrecision + computedRecall > 0 ? (2 * computedPrecision * computedRecall) / (computedPrecision + computedRecall) : 0;

  console.log(`[PROVENANCE METADATA]`);
  console.log(`- Generated By: ${canonical.provenance.generatedBy}`);
  console.log(`- Execution Mode: ${canonical.provenance.executionMode}`);
  console.log(`- Dynamic Artifact: ${canonical.provenance.dynamic}`);
  console.log(`[DYNAMIC MATHEMATICAL VERIFICATION]`);
  console.log(`- True Positives (TP): ${tp}`);
  console.log(`- False Positives (FP): ${fp}`);
  console.log(`- False Negatives (FN): ${fn}`);
  console.log(`- Computed Precision: ${(computedPrecision * 100).toFixed(1)}%`);
  console.log(`- Computed Recall: ${(computedRecall * 100).toFixed(1)}%`);
  console.log(`- Computed F1-Score: ${(computedF1 * 100).toFixed(1)}%`);

  const precisionDiff = Math.abs(evalSummary.overall.precision - computedPrecision);
  const recallDiff = Math.abs(evalSummary.overall.recall - computedRecall);
  const f1Diff = Math.abs(evalSummary.overall.f1Score - computedF1);

  if (precisionDiff > 0.001 || recallDiff > 0.001 || f1Diff > 0.001) {
    console.error('❌ ERROR: Mathematical contradiction detected in evaluation calculations!');
    process.exit(1);
  }

  console.log('✅ Dynamic evaluation metrics and provenance metadata are mathematically consistent.');
  console.log('====================================================');
}

validateResearchIntegrity().catch((err) => {
  console.error('Validation script execution failed:', err);
  process.exit(1);
});
