'use client';

import React, { useState } from 'react';
import { trackFixApplied, trackFixVerified } from '../../src/lib/analytics';

export default function AIFixPage() {
  const [loading, setLoading] = useState(false);
  const [aiResult, setAiResult] = useState<{
    engineType: string;
    provider?: string;
    confidenceScore: number;
    appliedFixDescription: string;
    remediatedCode: string;
    diff?: string;
    fallbackReason?: string;
    verified: boolean;
    verificationStatus: string;
  } | null>(null);
  const [error, setError] = useState<string | null>(null);

  const sampleCode = `function updateUser(user, name) {
  // Issue: Direct state mutation skips React re-render
  user.name = name;
  setUser(user);
}`;

  const sampleDefect = {
    ruleId: 'FIGM-REACT-03',
    ruleName: 'Avoid Direct React State Mutation',
    domain: 'PERFORMANCE',
    severity: 'CRITICAL',
    filePath: 'src/UserProfile.jsx',
    location: { start: { line: 3, column: 3 } },
    offendingCodeSnippet: 'user.name = name;\nsetUser(user);',
    remediation: 'Avoid direct state mutation; instantiate a new object reference.',
    standardReference: 'ISO 25010'
  };

  const handleGenerateAIFix = async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await fetch('/api/scan', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          code: sampleCode,
          fileName: 'UserProfile.jsx',
          action: 'ai-fix',
          defect: sampleDefect,
        }),
      });

      if (!res.ok) throw new Error(`Server returned status ${res.status}`);
      const data = await res.json();

      // The engine type, confidence score, remediated code, and diff below all come straight
      // from the real /api/scan response -- never substituted with plausible-looking invented
      // values when a field is missing. A response missing remediatedCode means the fix
      // genuinely didn't produce one (e.g. MANUAL_REVIEW_REQUIRED), which is a real, distinct
      // outcome the user needs to see, not something to paper over with fabricated "AI output."
      if (!data.remediatedCode) {
        throw new Error(data.error || data.fallbackReason || 'The fix pipeline did not return a remediated code candidate.');
      }

      setAiResult({
        engineType: data.engineType,
        provider: data.provider,
        confidenceScore: data.confidenceScore,
        appliedFixDescription: data.appliedFixDescription,
        remediatedCode: data.remediatedCode,
        diff: data.suggestedFix?.diff,
        fallbackReason: data.fallbackReason,
        verified: data.verified === true,
        verificationStatus: data.verificationStatus || 'UNRESOLVED',
      });
      trackFixApplied({ ruleId: sampleDefect.ruleId, strategy: data.engineType === 'AI_ASSISTED' ? 'AI_ASSISTED' : 'DETERMINISTIC' });
      trackFixVerified({ ruleId: sampleDefect.ruleId, verified: data.verified === true });
    } catch (err: any) {
      // Never fabricate a plausible-looking "AI fix result" (a specific confidence score,
      // invented code, an invented diff) when the request itself failed -- that would show the
      // user a fix that was never actually generated by anything. Report the failure honestly
      // instead; the user's code was NOT changed and no fix was produced.
      setAiResult(null);
      setError(err?.message || 'Failed to generate a fix — the request could not be completed.');
    } finally {
      setLoading(false);
    }
  };

  return (
    <div className="animate-fade-in" style={{ display: 'flex', flexDirection: 'column', gap: '24px' }}>
      <div>
        <div style={{ fontSize: '12px', color: '#a855f7', fontWeight: 700, textTransform: 'uppercase', letterSpacing: '0.6px', marginBottom: '4px' }}>
          Claude Opus 5 Engine Integration
        </div>
        <h1 style={{ fontSize: '26px', fontWeight: 800, color: '#f8fafc', letterSpacing: '-0.5px' }}>
          AI Fix Assistant
        </h1>
        <p style={{ color: '#94a3b8', fontSize: '14px', marginTop: '4px' }}>
          Generate high-confidence AI patches powered by Claude Opus 5 with deterministic AST fallback protection.
        </p>
      </div>

      <div className="glass-panel" style={{ padding: '24px' }}>
        <div style={{ display: 'flex', justifyContent: 'space-between', alignItems: 'center', marginBottom: '16px', flexWrap: 'wrap', gap: '12px' }}>
          <div>
            <div style={{ display: 'flex', gap: '8px', alignItems: 'center' }}>
              <span className="badge badge-domain">FIGM-REACT-03</span>
              <span style={{ fontSize: '10px', color: '#eab308', background: 'rgba(234, 179, 8, 0.1)', padding: '2px 8px', borderRadius: '4px', border: '1px solid rgba(234, 179, 8, 0.3)', fontWeight: 700 }}>
                Demonstration Benchmark Fixture
              </span>
            </div>
            <h2 style={{ fontSize: '18px', fontWeight: 700, color: '#f8fafc', marginTop: '6px' }}>
              Avoid Direct React State Mutation
            </h2>
            <div style={{ fontSize: '12px', color: '#94a3b8', marginTop: '2px' }}>
              Target: <code style={{ color: '#38bdf8' }}>src/UserProfile.jsx:3</code> &bull; Rule Severity: <strong style={{ color: '#ef4444' }}>CRITICAL</strong>
            </div>
          </div>

          <button
            onClick={handleGenerateAIFix}
            disabled={loading}
            className="btn-glow"
            style={{ padding: '10px 18px', fontSize: '13px' }}
          >
            {loading ? '🤖 Generating AI Fix via Claude...' : '⚡ Generate Claude AI Fix'}
          </button>
        </div>

        {error && (
          <div
            role="alert"
            style={{
              marginTop: '16px',
              padding: '10px 14px',
              borderRadius: '8px',
              background: 'rgba(239,68,68,0.1)',
              border: '1px solid rgba(239,68,68,0.3)',
              color: '#fca5a5',
              fontSize: '12px',
            }}
          >
            ⚠️ {error} No fix was generated and no code was changed.
          </div>
        )}

        {aiResult && (
          <div style={{ display: 'flex', flexDirection: 'column', gap: '16px', marginTop: '16px', borderTop: '1px solid rgba(255, 255, 255, 0.08)', paddingTop: '16px' }}>
            <div style={{ display: 'flex', gap: '12px', alignItems: 'center' }}>
              <span style={{ fontSize: '12px', fontWeight: 700, padding: '4px 10px', borderRadius: '6px', background: aiResult.engineType === 'AI_ASSISTED_FIX' ? 'rgba(56, 189, 248, 0.15)' : 'rgba(245, 158, 11, 0.15)', color: aiResult.engineType === 'AI_ASSISTED_FIX' ? '#38bdf8' : '#fbbf24', border: '1px solid currentColor' }}>
                Engine: {aiResult.engineType}{aiResult.provider ? ` (${aiResult.provider})` : ''}
              </span>
              <span style={{ fontSize: '12px', color: '#10b981', fontWeight: 700 }}>
                Confidence: {aiResult.confidenceScore}%
              </span>
              {aiResult.fallbackReason && (
                <span style={{ fontSize: '11px', color: '#f59e0b' }}>
                  (Fallback: {aiResult.fallbackReason})
                </span>
              )}
            </div>

            {/* The candidate code below is always shown, verified or not -- but whether it was
                actually confirmed to fix the violation (re-scanned, ruleId gone) must never be
                left ambiguous. A candidate that doesn't verify still gets a real, distinct
                remediatedCode from the engine, which can render identical to "Original Code"
                with no visual cue that nothing actually changed unless this banner says so. */}
            <div
              style={{
                fontSize: '12px',
                fontWeight: 700,
                padding: '8px 12px',
                borderRadius: '6px',
                background: aiResult.verified ? 'rgba(34,197,94,0.1)' : 'rgba(239,68,68,0.1)',
                border: `1px solid ${aiResult.verified ? 'rgba(34,197,94,0.3)' : 'rgba(239,68,68,0.3)'}`,
                color: aiResult.verified ? '#86efac' : '#fca5a5',
              }}
            >
              {aiResult.verified
                ? `✅ Verified: re-scanning the candidate code confirmed FIGM-REACT-03 no longer fires.`
                : `❌ Not verified (${aiResult.verificationStatus}): re-scanning the candidate code still detects FIGM-REACT-03, or the patch could not be confirmed. The code below is what the engine produced, but it does NOT resolve the violation.`}
            </div>

            <div style={{ fontSize: '13px', color: '#f8fafc', background: 'rgba(15, 23, 42, 0.6)', padding: '12px', borderRadius: '8px', border: '1px solid rgba(255, 255, 255, 0.08)' }}>
              💡 <strong>AI Remediation Strategy:</strong> {aiResult.appliedFixDescription}
            </div>

            <div style={{ display: 'grid', gridTemplateColumns: '1fr 1fr', gap: '16px' }}>
              <div>
                <div style={{ fontSize: '11px', color: '#ef4444', fontWeight: 700, marginBottom: '6px' }}>
                  🔴 Original Code:
                </div>
                <pre style={{ background: '#090d16', padding: '16px', borderRadius: '8px', border: '1px solid rgba(255, 255, 255, 0.08)', color: '#fca5a5', fontFamily: 'JetBrains Mono', fontSize: '12px', overflowX: 'auto' }}>
{sampleCode}
                </pre>
              </div>

              <div>
                <div style={{ fontSize: '11px', color: '#10b981', fontWeight: 700, marginBottom: '6px' }}>
                  🟢 AI Fixed Code:
                </div>
                <pre style={{ background: '#090d16', padding: '16px', borderRadius: '8px', border: '1px solid rgba(255, 255, 255, 0.08)', color: '#86efac', fontFamily: 'JetBrains Mono', fontSize: '12px', overflowX: 'auto' }}>
{aiResult.remediatedCode}
                </pre>
              </div>
            </div>

            {aiResult.diff && (
              <div>
                <div style={{ fontSize: '11px', color: '#38bdf8', fontWeight: 700, marginBottom: '6px' }}>
                  📄 Unified Git Diff Patch:
                </div>
                <pre style={{ background: '#090d16', padding: '14px', borderRadius: '8px', border: '1px solid rgba(255, 255, 255, 0.08)', color: '#38bdf8', fontFamily: 'JetBrains Mono', fontSize: '12px', overflowX: 'auto' }}>
{aiResult.diff}
                </pre>
              </div>
            )}
          </div>
        )}
      </div>
    </div>
  );
}
