import fs from 'node:fs';
import path from 'node:path';
import { CoverageBenchmarkEngine, TOOL_COMPARISON_MATRIX } from './tool-benchmark.js';
import { UserStudyEvaluator } from './user-study-evaluator.js';
import { EvaluationRunner } from './evaluation-runner.js';

export class ThesisGapExporter {
  public static exportAllChapters(): void {
    const outputDir = path.resolve(process.cwd(), 'docs/dissertation');
    if (!fs.existsSync(outputDir)) {
      fs.mkdirSync(outputDir, { recursive: true });
    }

    // NOTE: This exporter previously generated a "Chapter 4" document from
    // src/eval/repo-evaluator.ts's REPOSITORY_DATASET — 30 hand-typed records with invented
    // GitHub repo names/URLs (several do not exist, e.g. "exchangerates/dashboard",
    // "saasify/react-dash") and fabricated LOC/violation/score figures. No repositories were
    // ever cloned or scanned to produce those numbers, so the dataset and this generator block
    // were deleted rather than relabeled. The only real evaluation is the fixture-based
    // ground-truth benchmark below (Chapter 5), driven by benchmarks/ground-truth.json +
    // benchmarks/testbed.
    const staleCh4Path = path.join(outputDir, 'chapter4_large_scale_evaluation.md');
    if (fs.existsSync(staleCh4Path)) {
      fs.unlinkSync(staleCh4Path);
    }

    // --- Export Chapter 5: Empirical Validation, Precision/Recall & Benchmarking ---
    // The ONLY confusion matrix/precision/recall/F1 numbers this chapter reports come from a live
    // call to EvaluationRunner.runEvaluation() -- the exact same function that produces
    // benchmarks/eval-summary.json and docs/evidence/canonical-evaluation.json (the numbers shown
    // in the live UI at /analytics and via GET /api/research-metrics). A prior version of this
    // chapter instead read a hand-typed `EMPIRICAL_EXPERT_GROUND_TRUTH` constant that had silently
    // drifted from the real benchmark (18/3/1 vs. the real 19/2/0 at the time this was fixed) --
    // see docs/architecture/RESEARCH_METRICS_PIPELINE.md for the single-source-of-truth
    // architecture this chapter is now generated from.
    const evalResults = EvaluationRunner.runEvaluation();
    const coverage = CoverageBenchmarkEngine.calculateCoverageSummary();
    const rc = evalResults.ruleCoverage;

    const ch5Content = `# Chapter 5: Empirical Validation, Precision/Recall & Benchmarking

*Auto-generated by \`src/eval/thesis-gap-exporter.ts\` from a live \`EvaluationRunner.runEvaluation()\` call on every \`npm run research:evaluate\` / \`npm test\` run. Do not hand-edit this file -- edit the pipeline in \`src/eval/evaluation-runner.ts\` instead, and re-run to regenerate.*

## 5.0 Provenance

- **Dataset**: \`benchmarks/ground-truth.json\` (${rc.rulesWithGroundTruth} rules, hand-labelled) scored against fixture files in \`benchmarks/testbed\`
- **Generated at**: ${evalResults.timestamp}
- **Calculation method**: ${evalResults.calculationMethod}
- **Rule coverage**: ${rc.rulesWithGroundTruth} of ${rc.totalFigmRules} FIGM rules have empirical ground-truth coverage (${rc.coveredRuleIds.join(', ')}). The remaining ${rc.uncoveredRuleIds.length} rules (${rc.uncoveredRuleIds.join(', ')}) are verified only by unit-level positive/negative fixture tests, not by this benchmark -- see Section 5.1.1.

## 5.1 Precision, Recall, and F1-Score Metrics against Ground Truth

Automated evaluation: \`RuleExecutionEngine.analyzeFile\` (the identical engine the live product uses) is re-run against every fixture in \`benchmarks/testbed\`, and its diagnostics are diffed against the hand-labelled violations in \`benchmarks/ground-truth.json\`.

### Confusion Matrix
- **True Positives (TP)**: ${evalResults.overall.truePositives}
- **False Positives (FP)**: ${evalResults.overall.falsePositives}
- **False Negatives (FN)**: ${evalResults.overall.falseNegatives}

*(True Negatives are not reported: there is no well-defined "clean code that correctly triggers nothing" universe to count for a rule-based static-analysis benchmark, so Accuracy/Specificity/FPR/FNR -- which require TN -- are intentionally not computed or shown, rather than filled in with a placeholder.)*

### Calculated Performance Metrics
- **Precision**: ${(evalResults.overall.precision * 100).toFixed(2)}%
- **Recall (Sensitivity)**: ${(evalResults.overall.recall * 100).toFixed(2)}%
- **F1-Score**: ${(evalResults.overall.f1Score * 100).toFixed(2)}%

### 5.1.1 Rule Coverage Limitation

> **This benchmark measures ${rc.rulesWithGroundTruth} of FIGM's ${rc.totalFigmRules} rules only.** The Precision/Recall/F1 figures above must not be interpreted as "FIGM detects all 25 rules with ${(evalResults.overall.f1Score * 100).toFixed(1)}% accuracy" -- they describe detection accuracy strictly for the rule subset with hand-labelled ground truth: ${rc.coveredRuleIds.join(', ')}. Extending empirical ground-truth coverage to the remaining ${rc.uncoveredRuleIds.length} rules (${rc.uncoveredRuleIds.join(', ')}) is future work.

---

## 5.2 Comparative Analysis against Existing Tools

> **Qualitative capability comparison, not an empirical benchmark.** No competitor tool listed below was executed against FIGM's test corpus; every cell is a yes/no capability judgment based on each tool's public documentation, never a measured score, percentage, or timing.

| Tool | Static Analysis | Dynamic Profiling | AI Remediation | Framework Independent |
|---|---|---|---|---|
${TOOL_COMPARISON_MATRIX.map(t => `| **${t.tool}** | ${t.staticAnalysis ? '✅' : '❌'} | ${t.dynamicProfiling ? '✅' : '❌'} | ${t.aiRemediation ? '✅' : '❌'} | ${t.frameworkIndependent ? '✅' : '❌'} |`).join('\n')}

FIGM's rule set is structurally ${coverage.universalRules} universal (cross-framework) and ${coverage.frameworkSpecificRules} framework-specific rules out of ${coverage.totalRules} total, derived directly from the live rule specification (\`src/matrix/four-layer-meta-model.ts\`) -- this is a rule-set composition count, not a detection-accuracy claim.

---

## 5.3 AI Remediation & Patch Evaluation

> **NOT YET EMPIRICALLY MEASURED.** A prior version of this section reported a "Patch Generation Success Rate," "Compilation Success Rate," and "Violation Removal Rate" derived from hardcoded literals (\`totalDefectsIdentified = 450\`, \`patchesGenerated = 434\`, ...) that corresponded to no real AI remediation run -- no such benchmark has actually been executed. Those figures were removed rather than replaced with different unverified numbers.
>
> The AI remediation pipeline (\`src/ai/ai-remediation-pipeline.ts\`) does exist and does verify each fix by re-scanning the patched code and confirming the original violation is gone (see \`src/engine/remediation-engine.ts::validatePatch\` and \`tests/live-scan-e2e.test.ts\`/\`tests/ai-remediation.test.ts\` for the per-fix correctness tests this pass instead) -- but no aggregate "success rate across N defects" statistic has been computed against a real, reproducible defect corpus. Computing one honestly would require running the pipeline against every ground-truth violation in \`benchmarks/ground-truth.json\` and recording the real FIXED/PATCH_REJECTED/UNRESOLVED/MANUAL_REVIEW_REQUIRED outcome distribution -- tracked as future work, not fabricated here.
`;

    fs.writeFileSync(path.join(outputDir, 'chapter5_empirical_validation_and_benchmarks.md'), ch5Content, 'utf-8');

    // --- Export Chapter 6: User Usability Evaluation & Threats to Validity ---
    const { processUserStudyPipeline } = require('../../scripts/import-user-study.js');
    const realReport = processUserStudyPipeline();
    const userStudy = UserStudyEvaluator.calculateStudySummary();

    const isReal = realReport.provenance.isRealHumanData && realReport.provenance.validParticipantCount > 0;
    const participantStatusText = isReal
      ? `${realReport.provenance.validParticipantCount} / ${realReport.provenance.targetSampleSize} Valid Real Participants`
      : `0 / 85 Valid Real Participants (Collection Status: NOT_COLLECTED)`;

    const susDisplay = isReal
      ? `${realReport.metrics.susMean.toFixed(1)} / 100`
      : `PENDING REAL DATA (Formula Verification Test Score: 86.4 / 100 [SYNTHETIC_PIPELINE_TEST_DATA])`;

    const alphaDisplay = isReal
      ? `${realReport.metrics.cronbachAlpha.toFixed(3)}`
      : `PENDING REAL DATA (Formula Verification Test Alpha: 0.892 [SYNTHETIC_PIPELINE_TEST_DATA])`;

    const ch6Content = `# Chapter 6: User Usability Evaluation & Threats to Validity

## 6.1 Usability Evaluation Provenance & Status

- **Dataset Type**: ${isReal ? 'REAL_HUMAN_DATA' : 'SYNTHETIC_PIPELINE_TEST_DATA'}
- **Real Human Participant Count**: ${participantStatusText}
- **Data Collection Status**: ${realReport.provenance.collectionStatus}
- **System Usability Scale (SUS) Score**: ${susDisplay}
- **Cronbach's Alpha Reliability ($\\\\alpha$)**: ${alphaDisplay}

> **Academic Provenance Notice**: Real human participant data has not yet been collected (0/85 valid responses ingested). The questionnaire scoring pipeline formula has been verified using a synthetic pipeline test vector model (SYNTHETIC_PIPELINE_TEST_DATA). Live empirical human results will be computed dynamically upon ingesting responses via \`npm run research:user-study:import\`.

### Pipeline Verification Test Questionnaire Items (Formula Test Data)

- **Formula Test Sample Size**: ${userStudy.sampleSize} Profile Vectors
- **Overall User Satisfaction Mean (Test Model)**: ${userStudy.overallSatisfactionMean} / 5.00
- **Formula Test Cronbach's Alpha**: ${userStudy.cronbachAlpha}

| ID | Usability Question | Formula Test Mean (1-5) | StdDev |
|---|---|---|---|
${userStudy.questions.map(q => `| ${q.id} | ${q.questionText} | **${q.meanScore.toFixed(2)}** | ${q.stdDev.toFixed(2)} |`).join('\n')}

---

## 6.2 Threats to Validity

### Internal Validity
- Evaluated deterministic AST rules to prevent execution randomness.
- Controlled synthetic and real-world repository inputs.

### External Validity
- Generalizes across single-page applications built on **Next.js**, **React**, and **Angular**.

### Construct Validity
- Aligned directly with WCAG 2.1 AA accessibility and Core Web Vitals performance standards.
`;

    fs.writeFileSync(path.join(outputDir, 'chapter6_user_study_and_validity.md'), ch6Content, 'utf-8');

    console.log('[THESIS EXPORTER] Exported updated Markdown dissertation chapters to docs/dissertation/');
  }
}
